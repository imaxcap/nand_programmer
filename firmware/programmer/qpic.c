void qpic_encode_bch4(const uint8_t *data, uint32_t len, uint8_t *parity_out)
{
    uint64_t rem = 0;
    for (uint32_t i = 0; i < len; i++)
    {
        uint8_t top_byte = (uint8_t)((rem >> (BCH4_DEGREE - 8)) & 0xFF);
        uint8_t idx = top_byte ^ data[i];
        rem = ((rem << 8) & BCH4_MASK) ^ bch4_table[idx];
    }

    memset(parity_out, 0, QPIC_BCH4_PARITY_LEN);
    for (int bit = 0; bit < BCH4_DEGREE; bit++)
    {
        if ((rem >> (BCH4_DEGREE - 1 - bit)) & 1ULL)
        {
            parity_out[bit / 8] |= (uint8_t)(0x80 >> (bit % 8));
        }
    }
}

void qpic_encode_bch8(const uint8_t *data, uint32_t len, uint8_t *parity_out)
{
    bch8_rem_t rem = {{0, 0}};
    for (uint32_t i = 0; i < len; i++)
    {
        uint8_t top_byte = (uint8_t)((rem.words[1] >> (BCH8_DEGREE - 64 - 8)) & 0xFF);
        uint8_t idx = top_byte ^ data[i];

        rem.words[1] = ((rem.words[1] << 8) | (rem.words[0] >> 56)) & ((1ULL << (BCH8_DEGREE - 64)) - 1ULL);
        rem.words[0] = rem.words[0] << 8;

        rem.words[0] ^= bch8_table[idx].words[0];
        rem.words[1] ^= bch8_table[idx].words[1];
    }

    memset(parity_out, 0, QPIC_BCH8_PARITY_LEN);
    for (int bit = 0; bit < BCH8_DEGREE; bit++)
    {
        bool bit_val;
        if (bit < (BCH8_DEGREE - 64))
        {
            bit_val = ((rem.words[1] >> (BCH8_DEGREE - 64 - 1 - bit)) & 1ULL) != 0;
        }
        else
        {
            int low_bit_idx = BCH8_DEGREE - 1 - bit;
            bit_val = ((rem.words[0] >> low_bit_idx) & 1ULL) != 0;
        }

        if (bit_val)
        {
            parity_out[bit / 8] |= (uint8_t)(0x80 >> (bit % 8));
        }
    }
}

int qpic_interleave_page(const uint8_t *flat_in, uint8_t *raw_out, uint32_t page_size, uint32_t oob_size, qpic_ecc_mode_t ecc_mode)
{
    if (!flat_in || !raw_out || page_size == 0 || page_size % 512 != 0)
        return -1;

    uint32_t cw_count = page_size / 512;
    uint32_t cw_size = (ecc_mode == QPIC_ECC_BCH8) ? QPIC_BCH8_CW_SIZE : QPIC_BCH4_CW_SIZE;
    uint32_t parity_len = (ecc_mode == QPIC_ECC_BCH8) ? QPIC_BCH8_PARITY_LEN : QPIC_BCH4_PARITY_LEN;
    uint32_t pad_len = (ecc_mode == QPIC_ECC_BCH8) ? 2 : 4;
    uint32_t bbm_pos = page_size % cw_size;

    uint32_t min_oob = (cw_count * cw_size) - page_size;
    if (oob_size < min_oob)
        return -2;

    uint32_t raw_page_size = page_size + oob_size;
    memset(raw_out, 0xFF, raw_page_size);

    uint8_t cw_payload[QPIC_CW_DATA_BYTES];
    uint8_t parity[16];

    for (uint32_t cw = 0; cw < cw_count; cw++)
    {
        uint32_t in_offset = cw * QPIC_CW_DATA_BYTES;
        uint32_t out_offset = cw * cw_size;

        memset(cw_payload, 0xFF, sizeof(cw_payload));

        if (in_offset < page_size)
        {
            uint32_t avail = page_size - in_offset;
            if (avail > QPIC_CW_DATA_BYTES)
                avail = QPIC_CW_DATA_BYTES;
            memcpy(cw_payload, &flat_in[in_offset], avail);
        }

        // Calculate BCH parity over 516-byte codeword payload
        if (ecc_mode == QPIC_ECC_BCH8)
            qpic_encode_bch8(cw_payload, QPIC_CW_DATA_BYTES, parity);
        else
            qpic_encode_bch4(cw_payload, QPIC_CW_DATA_BYTES, parity);

        // Assemble into raw output:
        // 1. Pre-BBM data (bbm_pos bytes)
        memcpy(&raw_out[out_offset], &cw_payload[0], bbm_pos);
        // 2. BBM marker (1 byte, 0xFF)
        raw_out[out_offset + bbm_pos] = 0xFF;
        // 3. Post-BBM data (516 - bbm_pos bytes)
        memcpy(&raw_out[out_offset + bbm_pos + 1], &cw_payload[bbm_pos], QPIC_CW_DATA_BYTES - bbm_pos);
        // 4. Parity
        memcpy(&raw_out[out_offset + QPIC_CW_DATA_BYTES + 1], parity, parity_len);
        // 5. Padding
        memset(&raw_out[out_offset + QPIC_CW_DATA_BYTES + 1 + parity_len], 0xFF, pad_len);
    }

    return 0;
}

int qpic_deinterleave_page(const uint8_t *raw_in, uint8_t *flat_out, uint32_t page_size, uint32_t oob_size, qpic_ecc_mode_t ecc_mode)
{
    if (!raw_in || !flat_out || page_size == 0 || page_size % 512 != 0)
        return -1;

    uint32_t cw_count = page_size / 512;
    uint32_t cw_size = (ecc_mode == QPIC_ECC_BCH8) ? QPIC_BCH8_CW_SIZE : QPIC_BCH4_CW_SIZE;
    uint32_t bbm_pos = page_size % cw_size;

    uint32_t page_bytes_collected = 0;

    for (uint32_t cw = 0; cw < cw_count && page_bytes_collected < page_size; cw++)
    {
        uint32_t cw_start = cw * cw_size;

        // Part 1: before BBM (bbm_pos bytes)
        uint32_t part1_size = (bbm_pos < (page_size - page_bytes_collected)) ? bbm_pos : (page_size - page_bytes_collected);
        memcpy(&flat_out[page_bytes_collected], &raw_in[cw_start], part1_size);
        page_bytes_collected += part1_size;

        // Part 2: after BBM (516 - bbm_pos bytes)
        uint32_t part2_start = cw_start + bbm_pos + 1; // Skip 1 BBM byte
        uint32_t part2_avail = QPIC_CW_DATA_BYTES - bbm_pos;
        uint32_t part2_size = (part2_avail < (page_size - page_bytes_collected)) ? part2_avail : (page_size - page_bytes_collected);
        memcpy(&flat_out[page_bytes_collected], &raw_in[part2_start], part2_size);
        page_bytes_collected += part2_size;
    }

    return 0;
}

